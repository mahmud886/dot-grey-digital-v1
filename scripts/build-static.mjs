/**
 * Static build for cPanel / shared hosting (no Node server):
 *   1. `next build` with STATIC_EXPORT=1 → plain files in out/
 *   2. copy the PHP form endpoint into out/api/
 *   3. write out/.htaccess for clean URLs, the 404 page and caching
 * Upload the contents of out/ to public_html. See DEPLOY.md.
 */
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const out = join(root, "out");

const build = spawnSync("npx", ["next", "build"], {
  stdio: "inherit",
  env: { ...process.env, STATIC_EXPORT: "1", NEXT_PUBLIC_FORMS_ENDPOINT: "/api/forms.php" },
});
if (build.status !== 0) process.exit(build.status ?? 1);

mkdirSync(join(out, "api"), { recursive: true });
for (const f of ["forms.php", "config.example.php", ".htaccess"]) copyFileSync(join(root, "php", f), join(out, "api", f));
// A local config.php (never committed) is copied too, so a ready-to-upload folder can include it.
if (existsSync(join(root, "php", "config.php"))) copyFileSync(join(root, "php", "config.php"), join(out, "api", "config.php"));

writeFileSync(
  join(out, ".htaccess"),
  `# DotGrey Digital — static site on Apache (cPanel). Generated by scripts/build-static.mjs.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Uncomment to force HTTPS once the SSL certificate is active.
  # RewriteCond %{HTTPS} off
  # RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]

  # Uncomment to drop "www." (or adapt to add it).
  # RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]
  # RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]

  # Pages are files like work.html next to folders like work/ (for /work/<slug>), so Apache
  # must not add a slash to folder names or /work would never reach work.html.
  DirectorySlash Off

  # /about/ -> /about (canonical URLs have no trailing slash)
  RewriteCond %{DOCUMENT_ROOT}/$1.html -f
  RewriteRule ^(.+)/$ /$1 [L,R=301]

  # Clean URLs: /about serves about.html
  RewriteCond %{DOCUMENT_ROOT}/$1.html -f
  RewriteRule ^(.+)$ /$1.html [L]
</IfModule>

# The share image and favicon are exported without a file extension.
<FilesMatch "^(icon|opengraph-image)$">
  ForceType image/png
</FilesMatch>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), interest-cohort=()"
  # Hashed build assets never change: cache them for a year.
  <FilesMatch "\\.(js|css|woff2?|ttf)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  # Images and icons keep their names, so a month, then revalidate.
  <FilesMatch "\\.(svg|png|jpe?g|webp|avif|ico)$">
    Header set Cache-Control "public, max-age=2592000, stale-while-revalidate=86400"
  </FilesMatch>
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>

# Brotli where the host has it (smaller than gzip), gzip everywhere else.
<IfModule mod_brotli.c>
  AddOutputFilterByType BROTLI_COMPRESS text/html text/css text/javascript application/javascript application/json image/svg+xml text/xml application/xml text/plain
</IfModule>
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript application/json image/svg+xml text/xml application/xml text/plain
</IfModule>
`,
);

console.log("\nStatic site ready in out/. Upload its contents (including .htaccess and api/) to public_html.");
